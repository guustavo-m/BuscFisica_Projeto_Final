CREATE TABLE IF NOT EXISTS usuario (
  id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  tipo VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (tipo IN ('user','admin')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS materia (
  id_mat BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_mat TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS vestibulares (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  sigla VARCHAR(20) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS dificuldade (
  id_d BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grau VARCHAR(30) NOT NULL UNIQUE CHECK (grau IN ('Fácil','Médio','Difícil'))
);
CREATE TABLE IF NOT EXISTS topico (
  id_top BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_materia BIGINT NOT NULL REFERENCES materia(id_mat) ON UPDATE CASCADE ON DELETE RESTRICT,
  nome_top TEXT NOT NULL,
  UNIQUE(id_materia,nome_top)
);
CREATE TABLE IF NOT EXISTS resposta (
  id_resp BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resp_correta TEXT NOT NULL,
  explicacao_prof TEXT,
  contas_url TEXT,
  videoaula TEXT
);
CREATE TABLE IF NOT EXISTS questoes (
  idq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idvest BIGINT NOT NULL REFERENCES vestibulares(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  idresp BIGINT NOT NULL REFERENCES resposta(id_resp) ON UPDATE CASCADE ON DELETE RESTRICT,
  idtopico BIGINT NOT NULL REFERENCES topico(id_top) ON UPDATE CASCADE ON DELETE RESTRICT,
  graudif BIGINT NOT NULL REFERENCES dificuldade(id_d) ON UPDATE CASCADE ON DELETE RESTRICT,
  ano INTEGER CHECK (ano BETWEEN 1900 AND 2100),
  enunciado TEXT NOT NULL,
  alt_a TEXT NOT NULL, alt_b TEXT NOT NULL, alt_c TEXT NOT NULL, alt_d TEXT NOT NULL,
  alt_e TEXT, imagem_url TEXT
);
CREATE INDEX IF NOT EXISTS idx_questoes_vestibular ON questoes(idvest);
CREATE INDEX IF NOT EXISTS idx_questoes_topico ON questoes(idtopico);
CREATE INDEX IF NOT EXISTS idx_topico_materia ON topico(id_materia);
CREATE INDEX IF NOT EXISTS idx_questoes_dificuldade ON questoes(graudif);
CREATE INDEX IF NOT EXISTS idx_usuario_email ON usuario(email);

-- As tabelas são acessadas exclusivamente pela API Express.
-- Não exponha a service_role key no frontend/mobile. O RLS é ativado como defesa adicional.
ALTER TABLE usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE materia ENABLE ROW LEVEL SECURITY;
ALTER TABLE vestibulares ENABLE ROW LEVEL SECURITY;
ALTER TABLE dificuldade ENABLE ROW LEVEL SECURITY;
ALTER TABLE topico ENABLE ROW LEVEL SECURITY;
ALTER TABLE resposta ENABLE ROW LEVEL SECURITY;
ALTER TABLE questoes ENABLE ROW LEVEL SECURITY;
-- Nenhuma policy pública é criada: o acesso direto via chave anon permanece bloqueado.

-- View de listagem sem gabarito: a resposta só é consultada no detalhe autenticado.
CREATE OR REPLACE VIEW vw_questoes AS
SELECT
  q.idq,
  v.nome AS vestibular,
  v.sigla,
  t.nome_top AS topico,
  m.nome_mat AS materia,
  d.grau AS dificuldade,
  q.ano,
  q.enunciado,
  q.alt_a,
  q.alt_b,
  q.alt_c,
  q.alt_d,
  q.alt_e,
  q.imagem_url
FROM questoes q
JOIN vestibulares v ON q.idvest = v.id
JOIN topico t ON q.idtopico = t.id_top
JOIN materia m ON t.id_materia = m.id_mat
JOIN dificuldade d ON q.graudif = d.id_d;
